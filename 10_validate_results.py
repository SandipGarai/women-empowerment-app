# Step 3: Helper functions for validation rules
# These rules are conservative flags for human review.

def key_text(value):
    """Lowercase normalized text for matching."""
    text = "" if pd.isna(value) else str(value)
    text = re.sub(r"\s+", " ", text).strip().lower()
    return text


def is_missing_like(value):
    """Flag answers that should usually be treated as missing/unsure.

    Note: 'Not mentioned/NA' is treated as a valid response category because
    respondents or enumerators explicitly recorded it. Only genuinely empty
    or uninformative entries are flagged here. Blank cells are already removed
    during cleaning, so this mainly catches stray non-answers that survived.
    """
    text = key_text(value)
    if text == "":
        return True
    missing_terms = [
        "unsure",
        "not available",
        "no information",
        "no response",
    ]
    return any(term in text for term in missing_terms)


def suggested_theme(question, respondent_group):
    """Suggest a theme from question text for comparison with assigned theme."""
    q = key_text(question)
    group = key_text(respondent_group)
    combined = f"{group} {q}"

    # Matrix-specific overrides (these sub-items belong to their matrix theme)
    if "involvement in activities" in combined:
        return "Women Empowerment and Panchayat Participation"
    if "rate challenges" in combined:
        return "Challenges and Constraints"

    # ICT and Digital Access
    ict_terms = [
        "mobile", "phone", "digital", "technology", "whatsapp",
        "computer", "smartphone", "internet", "e-governance", "online",
        "social media", "sms",
    ]
    if any(term in combined for term in ict_terms):
        return "ICT and Digital Access"
    # Check "ict" and "data" as whole words to avoid false matches
    if re.search(r"\bict\b", combined) or re.search(r"\bdata\b", combined):
        return "ICT and Digital Access"

    # Agriculture and Livelihood
    if any(term in combined for term in [
        "crop", "livestock", "irrigation", "land", "agriculture",
        "technique", "farming", "kharif", "rabi", "paddy", "wheat", "vegetable",
    ]):
        return "Agriculture and Livelihood"

    # Traditional vs Formal Governance
    if any(term in combined for term in [
        "traditional", "pradhan", "parha", "dispute", "council",
        "mahto", "pahan",
    ]):
        return "Traditional vs Formal Governance"

    # Challenges and Constraints
    if any(term in combined for term in [
        "challenge", "difficulty", "hurdle", "barrier", "patriarchy",
        "obstacle", "problem", "opposition",
    ]):
        return "Challenges and Constraints"

    # Women Empowerment and Panchayat Participation
    if any(term in combined for term in [
        "political journey", "participation", "decision", "gram sabha",
        "opinion", "planning", "empowerment", "mobility", "reservation",
        "proxy rule", "confidence", "respect", "leadership experience",
        "contest", "elected", "representation", "raise issues", "women issues",
    ]):
        return "Women Empowerment and Panchayat Participation"

    # Respondent Profile
    # Education as a topic (e.g., "issues related to education") is not profile.
    # Only the respondent's own education level/qualification is profile.
    profile_terms = [
        "gender", "age", "community", "marital", "occupation",
        "position held", "caste", "tribe", "name", "village", "panchayat",
        "block", "district", "income",
    ]
    if any(term in combined for term in profile_terms):
        return "Respondent Profile"
    if "education" in combined and any(term in combined for term in [
        "education level", "educational qualification", "your education", "education of the respondent"
    ]):
        return "Respondent Profile"

    # General Public awareness/access
    if "general public" in group and any(term in combined for term in [
        "mukhiya", "scheme", "help", "problem", "awareness", "access",
    ]):
        return "General Public: Awareness and Access"

    return ""


# %%
# Step 4: Flag questions where missing-like answers dominate
# These need a decision: report as-is, exclude missing from denominator, or describe as data gap.

missing_rows = all_results[all_results["answer"].apply(is_missing_like)].copy()

missing_share_by_question = (
    missing_rows.groupby(
        ["table_id", "theme", "result_type", "respondent_group", "question_no", "question", "denominator_n"],
        dropna=False,
    )
    .agg(missing_count=("count", "sum"))
    .reset_index()
)

missing_share_by_question["missing_percent"] = (
    missing_share_by_question["missing_count"]
    / missing_share_by_question["denominator_n"]
    * 100
).round(2)

missing_dominant_questions = missing_share_by_question[
    missing_share_by_question["missing_percent"] >= 30
].sort_values("missing_percent", ascending=False)

display(missing_dominant_questions)


# %%
# Step 5: Create an alternative table excluding missing-like answers
# This does not replace the main table. It supports interpretation where needed.

nonmissing_results = all_results[~all_results["answer"].apply(is_missing_like)].copy()

nonmissing_denominators = (
    nonmissing_results.groupby(["table_id"], dropna=False)
    .agg(nonmissing_denominator_n=("count", "sum"))
    .reset_index()
)

results_excluding_missing = nonmissing_results.merge(
    nonmissing_denominators,
    on="table_id",
    how="left",
)

results_excluding_missing["percent_excluding_missing"] = (
    results_excluding_missing["count"]
    / results_excluding_missing["nonmissing_denominator_n"]
    * 100
).round(2)

display(results_excluding_missing.head(20))


# %%
# Step 6: Flag highly fragmented questions
# Many answer categories can mean open-ended data still needs thematic coding.

fragmentation_review = table_index.copy()
fragmentation_review["answer_rows"] = pd.to_numeric(fragmentation_review["answer_rows"], errors="coerce")
fragmentation_review["denominator_n"] = pd.to_numeric(fragmentation_review["denominator_n"], errors="coerce")
fragmentation_review["category_to_n_ratio"] = (
    fragmentation_review["answer_rows"] / fragmentation_review["denominator_n"]
).round(2)

high_fragmentation_questions = fragmentation_review[
    (fragmentation_review["answer_rows"] >= 8)
    | (fragmentation_review["category_to_n_ratio"] >= 0.50)
].sort_values(["answer_rows", "category_to_n_ratio"], ascending=False)

# Check whether thematic coding has been applied to any fragmented questions
THEMATIC_DIR = PROJECT_DIR / "outputs" / "thematic_coding"
THEMATIC_FREQ_PATH = THEMATIC_DIR / "thematic_frequencies.csv"
coded_questions = set()
if THEMATIC_FREQ_PATH.exists():
    thematic_freq = pd.read_csv(THEMATIC_FREQ_PATH)
    coded_questions = set(zip(thematic_freq["respondent_group"], thematic_freq["question_no"]))
    high_fragmentation_questions["thematically_coded"] = high_fragmentation_questions.apply(
        lambda r: (r["respondent_group"], r["question_no"]) in coded_questions,
        axis=1,
    )
else:
    high_fragmentation_questions["thematically_coded"] = False

display(high_fragmentation_questions.head(40))


# %%
# Step 7: Review possible theme mismatches
# This compares assigned theme to a simple independent suggestion.

theme_assignment_review = table_index.copy()
theme_assignment_review["suggested_theme"] = theme_assignment_review.apply(
    lambda row: suggested_theme(row["question"], row["respondent_group"]),
    axis=1,
)

theme_assignment_review["needs_theme_review"] = (
    (theme_assignment_review["suggested_theme"] != "")
    & (theme_assignment_review["theme"] != theme_assignment_review["suggested_theme"])
)

theme_mismatch_review = theme_assignment_review[
    theme_assignment_review["needs_theme_review"]
].sort_values(["respondent_group", "question_no"])

display(theme_mismatch_review.head(50))


# %%
# Step 8: Validate single-response and multi-response count logic
# Single-response table totals should generally equal denominator.
# Multi-response table totals may exceed denominator.

count_check = table_index.copy()
count_check["denominator_n"] = pd.to_numeric(count_check["denominator_n"], errors="coerce")
count_check["total_count"] = pd.to_numeric(count_check["total_count"], errors="coerce")

count_check["count_minus_denominator"] = (
    count_check["total_count"] - count_check["denominator_n"]
)

count_check["count_logic_flag"] = ""

count_check.loc[
    (count_check["result_type"] == "single_response")
    & (count_check["count_minus_denominator"] != 0),
    "count_logic_flag",
] = "single_response_total_not_equal_denominator"

count_check.loc[
    (count_check["result_type"] == "multi_response")
    & (count_check["count_minus_denominator"] < 0),
    "count_logic_flag",
] = "multi_response_total_less_than_denominator_check_missing_categories"

single_vs_multi_response_check = count_check[
    count_check["count_logic_flag"] != ""
].sort_values(["result_type", "respondent_group", "question_no"])

display(single_vs_multi_response_check)


# %%
# Step 8B: Identify likely matrix or repeated-subquestion tables
# These are not necessarily data errors. They need restructuring so each
# sub-question has its own denominator and result table.

matrix_question_patterns = [
    "on a scale",
    "rate challenges",
    "change since becoming representative",
    "do you feel there has been a change",
]

def is_likely_matrix(row):
    """Flag rows that look like matrix questions but have not yet been restructured."""
    q_text = key_text(row["question"])
    q_no = str(row["question_no"])
    # Already-restructured sub-items have decimal question numbers like 19.1, 21.3
    if "." in q_no:
        return False
    return any(pattern in q_text for pattern in matrix_question_patterns)

likely_matrix_questions = count_check[count_check.apply(is_likely_matrix, axis=1)].copy()

likely_matrix_questions["recommended_treatment"] = (
    "Restructure as matrix/sub-question results before final charting."
)

display(likely_matrix_questions)


# %%
# Step 9: Create validation action list
# This gives a practical next-action label for each flagged table.

validation_actions = []

for _, row in missing_dominant_questions.iterrows():
    validation_actions.append(
        {
            "table_id": row["table_id"],
            "issue_type": "missing_dominant",
            "respondent_group": row["respondent_group"],
            "question_no": row["question_no"],
            "question": row["question"],
            "severity": "medium",
            "suggested_action": "Decide whether to report missing-like answers or use the excluding-missing table for interpretation.",
        }
    )

for _, row in high_fragmentation_questions.iterrows():
    if row.get("thematically_coded", False):
        action_text = "Thematic coding applied; review outputs/thematic_coding/review/thematic_coding_review.xlsx if adjustments are needed."
    else:
        action_text = "Review whether this open-ended question needs additional thematic coding."
    validation_actions.append(
        {
            "table_id": row["table_id"],
            "issue_type": "high_fragmentation",
            "respondent_group": row["respondent_group"],
            "question_no": row["question_no"],
            "question": row["question"],
            "severity": "low" if row.get("thematically_coded", False) else "medium",
            "suggested_action": action_text,
        }
    )

for _, row in theme_mismatch_review.iterrows():
    validation_actions.append(
        {
            "table_id": row["table_id"],
            "issue_type": "theme_review",
            "respondent_group": row["respondent_group"],
            "question_no": row["question_no"],
            "question": row["question"],
            "severity": "low",
            "suggested_action": f"Check assigned theme '{row['theme']}' against suggested theme '{row['suggested_theme']}'.",
        }
    )

for _, row in single_vs_multi_response_check.iterrows():
    validation_actions.append(
        {
            "table_id": row["table_id"],
            "issue_type": "count_logic",
            "respondent_group": row["respondent_group"],
            "question_no": row["question_no"],
            "question": row["question"],
            "severity": "high",
            "suggested_action": row["count_logic_flag"],
        }
    )

validation_action_list = pd.DataFrame(validation_actions)

if len(validation_action_list) > 0:
    validation_action_list = validation_action_list.drop_duplicates().sort_values(
        ["severity", "issue_type", "respondent_group", "question_no"],
        ascending=[True, True, True, True],
    )

display(validation_action_list.head(60))


