# %%
# Step 9: Generate validation status summary
# This is a one-page traffic-light summary for quick review.

# Load workbook overview for respondent counts
overview_path = PROJECT_DIR / "outputs" / "exploration" / "workbook_overview.csv"
if overview_path.exists():
    overview = pd.read_csv(overview_path)
else:
    overview = pd.DataFrame(columns=["sheet", "respondent_columns"])

# Expected number of respondents per sheet. UPDATE THIS whenever respondents are
# added to or removed from Surveys.xlsx, otherwise validation reports a false FAIL.
# Last updated for the 2026-09-01 workbook (General Public grew from 52 to 53).
expected_counts = {
    "General Public": 53,
    "Govt Officials": 11,
    "Mahila Mukhiya": 8,
    "Traditional Leader": 5,
    "Women Representative": 8,
}

status_rows = []
for _, row in overview.iterrows():
    sheet = row["sheet"]
    actual = row["respondent_columns"]
    exp = expected_counts.get(sheet, None)
    if exp and actual == exp:
        status_rows.append({"check": f"Respondent count: {sheet}", "status": "PASS", "note": f"{actual} respondents as expected"})
    else:
        status_rows.append({"check": f"Respondent count: {sheet}", "status": "FAIL", "note": f"Expected {exp}, found {actual}"})

matrix_count = len(likely_matrix_questions)
status_rows.append({
    "check": "Matrix questions need restructuring",
    "status": "PASS" if matrix_count == 0 else "CHECK",
    "note": f"{matrix_count} matrix question tables flagged" if matrix_count > 0 else "All matrix questions correctly structured",
})

missing_count = len(missing_dominant_questions)
status_rows.append({
    "check": "Missing-dominant questions",
    "status": "PASS" if missing_count == 0 else "CHECK",
    "note": f"{missing_count} questions have ≥30% 'Not mentioned/Do not know' answers" if missing_count > 0 else "No missing-dominant questions",
})

frag_count = len(high_fragmentation_questions)
if "thematically_coded" in high_fragmentation_questions.columns:
    # Count unique (group, question_no) pairs that have thematic coding
    coded_count = high_fragmentation_questions[high_fragmentation_questions["thematically_coded"]][
        ["respondent_group", "question_no"]
    ].drop_duplicates().shape[0]
else:
    coded_count = 0
if frag_count == 0:
    frag_status = "PASS"
    frag_note = "No fragmented questions"
elif coded_count > 0:
    frag_status = "CHECK"
    frag_note = f"{frag_count} question tables flagged; {coded_count} unique questions thematically coded (review workbook available)"
else:
    frag_status = "CHECK"
    frag_note = f"{frag_count} question tables may need thematic coding"
status_rows.append({
    "check": "Highly fragmented open-ended questions",
    "status": frag_status,
    "note": frag_note,
})

high_count = len(validation_action_list[validation_action_list["severity"] == "high"])
status_rows.append({
    "check": "High-severity count logic errors",
    "status": "PASS" if high_count == 0 else "FAIL",
    "note": f"{high_count} high-severity issues found" if high_count > 0 else "No high-severity count logic errors",
})

theme_count = len(theme_mismatch_review)
status_rows.append({
    "check": "Theme assignment mismatches",
    "status": "PASS" if theme_count == 0 else "CHECK",
    "note": f"{theme_count} question tables have suggested theme different from assigned" if theme_count > 0 else "No theme mismatches",
})

single_pct_check = count_check[(count_check["result_type"] == "single_response") & (count_check["count_minus_denominator"] != 0)]
status_rows.append({
    "check": "Single-response percentages > 100",
    "status": "PASS" if len(single_pct_check) == 0 else "FAIL",
    "note": f"{len(single_pct_check)} single-response tables exceed 100%" if len(single_pct_check) > 0 else "0 single-response tables exceed 100%",
})

status_rows.append({
    "check": "Total nonblank responses processed",
    "status": "PASS",
    "note": f"{len(all_results):,} result rows generated",
})

validation_status_summary = pd.DataFrame(status_rows)
validation_status_summary.to_csv(VALIDATION_DIR / "validation_status_summary.csv", index=False)
print("\nValidation status summary:")
print(validation_status_summary.to_string(index=False))


print("\nSaved validation outputs to:")
print(VALIDATION_DIR)
